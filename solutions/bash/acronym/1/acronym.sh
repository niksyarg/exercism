#!/usr/bin/env bash

main () {
    # 1. Заменяем дефисы на пробелы
    local cleaned="${1//-/ }"
    
    # 2. Удаляем всю пунктуацию, оставляя только буквы, цифры и пробелы
    cleaned="${cleaned//[^a-zA-Z0-9 ]/}"
    
    local acronym=""
    
    # 3. Перебираем слова и собираем первую букву каждого слова
    for word in $cleaned; do
        # Берем первый символ слова (${word:0:1})
        acronym+="${word:0:1}"
    done
    
    # 4. Переводим результат в верхний регистр и выводим
    echo "${acronym^^}"
}

# Передаем все позиционные аргументы в функцию main
main "$@"
